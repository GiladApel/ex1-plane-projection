"""Run the full benchmark matrix and write docs/experiment/benchmark.md.

python scripts/bench_matrix.py [--size 500] [--frames 100]
"""
import argparse
import csv
import io
import os
import platform
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "scripts" / "bench.py"
THREADS = [1, 2, 4, 8, 16]


def run_bench(extra: list[str], env_threads: int | None = None) -> list[dict]:
    env = dict(os.environ)
    if env_threads is not None:
        env["NUMBA_NUM_THREADS"] = str(env_threads)
    out = subprocess.run([sys.executable, str(BENCH), "--csv", *extra], env=env, capture_output=True, text=True, check=True)
    return list(csv.DictReader(io.StringIO(out.stdout)))


def table(rows: list[dict], columns: list[str], headers: list[str]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(r[c] for c in columns) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, default=500)
    parser.add_argument("--frames", type=int, default=100)
    args = parser.parse_args()
    common = ["--size", str(args.size), "--frames", str(args.frames)]

    matrix = []
    for backend, frames in (("numba", args.frames), ("numpy", max(20, args.frames // 4))):
        matrix += run_bench(
            ["--dtype", "uint8", "uint16", "uint32", "--planes", "oblique", "axis", "--backend", backend,
             "--interp", "nearest", "trilinear", "--size", str(args.size), "--frames", str(frames)]
        )
    scaling = []
    for threads in THREADS:
        row = run_bench(["--backend", "numba", *common], threads)[0]
        row["threads"] = str(threads)
        scaling.append(row)

    text = f"""# Benchmark results

Volume {args.size}^3 random data, {platform.processor()}, Python {platform.python_version()}.
Projection time only (plane in, matrix out). Numba runs use {args.frames} planes, NumPy runs
{max(20, args.frames // 4)}. Generated by `python scripts/bench_matrix.py`.

## Backend x dtype x sampling x plane orientation

{table(matrix, ["backend", "interp", "dtype", "planes", "median_fps", "p95_ms", "min_fps"],
       ["Backend", "Sampling", "dtype", "Planes", "Median fps", "p95 ms", "Slowest frame fps"])}

## Numba thread scaling (uint8, nearest, oblique)

{table(scaling, ["threads", "median_fps", "p95_ms"], ["Threads", "Median fps", "p95 ms"])}
"""
    target = ROOT / "docs" / "experiment" / "benchmark.md"
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
